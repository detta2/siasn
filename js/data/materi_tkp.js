<li><b>Disiplin itu harian.</b> Terlambat, mangkir, menunda pekerjaan — opsi yang menormalisasi ("sekali-sekali tidak apa") ber-skor rendah. Skor 5 = konsisten + memperbaiki sistem (mis. usul evaluasi berkala).</li>
